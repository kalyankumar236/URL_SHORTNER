-- URL Shortener schema. Portable SQL (H2 PostgreSQL mode + PostgreSQL).

CREATE TABLE link (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    short_code       VARCHAR(64)  NOT NULL,
    destination_url  VARCHAR(2048) NOT NULL,
    status           VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    custom_alias     BOOLEAN      NOT NULL DEFAULT FALSE,
    expires_at       TIMESTAMP    NULL,
    created_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by       VARCHAR(128) NULL,
    CONSTRAINT uk_link_short_code UNIQUE (short_code),
    CONSTRAINT ck_link_status CHECK (status IN ('ACTIVE', 'DISABLED', 'EXPIRED'))
);

-- Supports expiry sweeps and status filtering.
CREATE INDEX idx_link_status_expires ON link (status, expires_at);

CREATE TABLE click_event (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_id          BIGINT       NOT NULL,
    occurred_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    response_status  INT          NOT NULL,
    client_hash      VARCHAR(64)  NULL,
    referrer_host    VARCHAR(255) NULL,
    ua_class         VARCHAR(32)  NULL,
    CONSTRAINT fk_click_link FOREIGN KEY (link_id) REFERENCES link (id) ON DELETE CASCADE
);

-- Supports range and daily aggregation per link.
CREATE INDEX idx_click_link_time ON click_event (link_id, occurred_at);

-- Idempotency keys for safe retry of supported mutating operations.
CREATE TABLE idempotency_key (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key_value    VARCHAR(128) NOT NULL,
    scope        VARCHAR(64)  NOT NULL,
    response_ref VARCHAR(128) NULL,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_idempotency UNIQUE (scope, key_value)
);
